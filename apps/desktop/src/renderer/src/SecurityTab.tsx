import { formatLocalTime } from "@lc/core";
import { App as AntApp, Alert, Button, Card, Form, Input, InputNumber, Modal, Space, Switch, Tag, Typography } from "antd";
import { useCallback, useEffect, useState } from "react";
import type { SecurityStatus } from "../../shared/api";
import { useI18n } from "./i18n";
import RestoreDialog from "./RestoreDialog";

const DAY = 86_400_000;

export default function SecurityTab() {
  const { t, errorText } = useI18n();
  const { message } = AntApp.useApp();
  const [st, setSt] = useState<SecurityStatus | null>(null);
  const [verify, setVerify] = useState<{ ok: boolean; problems: string[] } | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [exporting, setExporting] = useState(false);
  const [restoring, setRestoring] = useState(false);
  const [pw, setPw] = useState({ a: "", b: "" });

  const load = useCallback(async () => {
    const r = await window.lc.getSecurityStatus();
    if (r.ok) setSt(r.data);
    else void message.error(errorText(r));
  }, [message, errorText]);

  useEffect(() => {
    void load();
  }, [load]);

  const doVerify = async () => {
    setBusy("verify");
    const r = await window.lc.verifyDatabase();
    setBusy(null);
    if (r.ok) setVerify(r.data);
    else void message.error(errorText(r));
  };

  const doExport = async () => {
    setBusy("export");
    const r = await window.lc.createBackup(pw.a);
    setBusy(null);
    if (!r.ok) return void message.error(errorText(r));
    if (!r.data) return; // 用户在保存对话框里取消
    setExporting(false);
    setPw({ a: "", b: "" });
    void message.success(t("sec.backupDone", { name: r.data.fileName }));
    await load();
  };

  const setAuto = async (input: { enabled?: boolean; keep?: number }) => {
    const r = await window.lc.setAutoBackup(input);
    if (r.ok) setSt(r.data);
    else void message.error(errorText(r));
  };

  const snapshotNow = async () => {
    setBusy("auto");
    const r = await window.lc.runAutoBackupNow();
    setBusy(null);
    if (r.ok) {
      setSt(r.data);
      void message.success(t("sec.autoGenerated"));
    } else void message.error(errorText(r));
  };

  if (!st) return null;
  const old = st.lastBackupAt ? Date.now() - new Date(st.lastBackupAt).getTime() > 30 * DAY : false;
  const mismatch = pw.b !== "" && pw.a !== pw.b;

  return (
    <Space direction="vertical" style={{ width: "100%" }} size="middle">
      <Card size="small" title={t("sec.encryption")} extra={<Tag color={st.encrypted ? "green" : "red"}>{t(st.encrypted ? "sec.encrypted" : "sec.notEncrypted")}</Tag>}>
        <Typography.Paragraph type="secondary">{t("sec.encryptedDesc")}</Typography.Paragraph>
        <Typography.Text type="secondary">
          {t("sec.dataDir")}：<Typography.Text code>{st.dataDir}</Typography.Text>
        </Typography.Text>
        <div style={{ marginTop: 8 }}>
          <Button loading={busy === "verify"} onClick={doVerify}>
            {t("sec.verify")}
          </Button>
        </div>
        {verify && <Alert style={{ marginTop: 8 }} showIcon type={verify.ok ? "success" : "error"} message={verify.ok ? t("sec.verifyOk") : t("sec.verifyBad", { problems: verify.problems.join("；") })} />}
      </Card>

      <Card size="small" title={t("sec.backupTitle")}>
        <Typography.Paragraph type="secondary">{t("sec.backupDesc")}</Typography.Paragraph>
        <Alert
          style={{ marginBottom: 12 }}
          showIcon
          type={st.lastBackupAt ? (old ? "warning" : "success") : "warning"}
          message={st.lastBackupAt ? t("sec.lastBackup", { time: formatLocalTime(st.lastBackupAt) }) : t("sec.neverBackup")}
          description={old ? t("sec.backupOld") : undefined}
        />
        <Space>
          <Button type="primary" onClick={() => setExporting(true)}>
            {t("sec.exportBackup")}
          </Button>
          <Button onClick={() => setRestoring(true)}>{t("sec.restore")}</Button>
        </Space>
      </Card>

      <Card size="small" title={t("sec.autoTitle")}>
        <Typography.Paragraph type="secondary">{t("sec.autoDesc")}</Typography.Paragraph>
        <Space wrap style={{ marginBottom: 8 }}>
          <Switch checked={st.auto.enabled} onChange={(v) => void setAuto({ enabled: v })} /> <span>{t("sec.autoEnable")}</span>
          <span style={{ marginLeft: 16 }}>{t("sec.autoKeep")}</span>
          <InputNumber min={1} max={60} value={st.auto.keep} onChange={(v) => v && void setAuto({ keep: v })} />
          <Button loading={busy === "auto"} onClick={snapshotNow}>
            {t("sec.autoNow")}
          </Button>
          <Button onClick={() => void window.lc.revealBackupFolder()}>{t("sec.openFolder")}</Button>
        </Space>
        {st.auto.items.length === 0 ? (
          <Typography.Text type="secondary">{t("sec.autoNone")}</Typography.Text>
        ) : (
          <div>
            {st.auto.items.map((i) => (
              <div key={i.name}>
                <Typography.Text code>{i.name}</Typography.Text> <Typography.Text type="secondary">{formatLocalTime(i.at)} · {(i.bytes / 1024).toFixed(0)} KB</Typography.Text>
              </div>
            ))}
          </div>
        )}
      </Card>

      <Modal
        title={t("sec.exportBackup")}
        open={exporting}
        onCancel={() => {
          setExporting(false);
          setPw({ a: "", b: "" });
        }}
        onOk={doExport}
        okText={t("sec.exportBackup")}
        cancelText={t("btn.cancel")}
        okButtonProps={{ disabled: pw.a.length < 8 || pw.a !== pw.b, loading: busy === "export" }}
        destroyOnClose
      >
        <Alert type="warning" showIcon message={t("sec.passwordWarn")} style={{ marginBottom: 12 }} />
        <Form layout="vertical">
          <Form.Item label={t("sec.password")} extra={t("sec.passwordRule")}>
            <Input.Password value={pw.a} onChange={(e) => setPw({ ...pw, a: e.target.value })} autoComplete="new-password" />
          </Form.Item>
          <Form.Item label={t("sec.passwordConfirm")} validateStatus={mismatch ? "error" : undefined} help={mismatch ? t("sec.passwordMismatch") : undefined}>
            <Input.Password value={pw.b} onChange={(e) => setPw({ ...pw, b: e.target.value })} autoComplete="new-password" />
          </Form.Item>
        </Form>
      </Modal>

      <RestoreDialog open={restoring} onClose={() => setRestoring(false)} />
    </Space>
  );
}
